"""
Unit tests for the AST-based SQL Validator.
Ensures strict SELECT-only query execution, blocks DDL/DML mutations,
prevents multi-statement SQL injection, and validates code fence sanitization.
"""

import pytest

from src.sql_agent.sql_validator import SQLValidationResult, SQLValidator


class TestSQLValidator:
    """Test suite for SQLValidator security and correctness rules."""

    def test_valid_simple_select(self):
        """Allows simple SELECT statements."""
        query = "SELECT id, name, country FROM customers;"
        result: SQLValidationResult = SQLValidator.validate(query)
        assert result.is_valid is True
        assert result.cleaned_query == "SELECT id, name, country FROM customers"
        assert result.error_message is None

    def test_valid_complex_join_and_aggregations(self):
        """Allows complex queries with JOINs, GROUP BY, and aggregations."""
        query = (
            "SELECT c.name, SUM(o.total_amount) AS total_revenue "
            "FROM customers c "
            "JOIN orders o ON c.id = o.customer_id "
            "WHERE o.status = 'completed' "
            "GROUP BY c.name "
            "ORDER BY total_revenue DESC "
            "LIMIT 5;"
        )
        result = SQLValidator.validate(query)
        assert result.is_valid is True
        assert "total_revenue" in result.cleaned_query

    def test_valid_cte_query(self):
        """Allows CTE queries starting with WITH ... SELECT."""
        query = (
            "WITH high_value_orders AS ("
            "    SELECT * FROM orders WHERE total_amount > 5000"
            ") "
            "SELECT customer_id, COUNT(*) FROM high_value_orders GROUP BY customer_id;"
        )
        result = SQLValidator.validate(query)
        assert result.is_valid is True

    def test_sanitizes_markdown_code_fences(self):
        """Properly strips markdown ```sql and ``` fences generated by LLMs."""
        raw = "```sql\nSELECT name, price FROM products WHERE price > 500;\n```"
        result = SQLValidator.validate(raw)
        assert result.is_valid is True
        assert result.cleaned_query == "SELECT name, price FROM products WHERE price > 500"

    def test_rejects_empty_and_whitespace_queries(self):
        """Rejects empty string or whitespace queries."""
        assert SQLValidator.validate("").is_valid is False
        assert SQLValidator.validate("   \n\t  ").is_valid is False

    @pytest.mark.parametrize(
        "forbidden_query, expected_keyword",
        [
            ("DROP TABLE customers;", "DROP"),
            ("DELETE FROM orders WHERE id = 1;", "DELETE"),
            ("UPDATE products SET price = 0 WHERE id = 2;", "UPDATE"),
            ("INSERT INTO customers (name) VALUES ('Hacker');", "INSERT"),
            ("TRUNCATE TABLE orders;", "TRUNCATE"),
            ("ALTER TABLE products ADD COLUMN secret VARCHAR(50);", "ALTER"),
            ("CREATE TABLE backdoor (id INT);", "CREATE"),
        ],
    )
    def test_rejects_mutating_and_ddl_queries(self, forbidden_query: str, expected_keyword: str):
        """Blocks all mutating DDL and DML operations."""
        result = SQLValidator.validate(forbidden_query)
        assert result.is_valid is False
        assert result.error_message is not None
        assert (
            expected_keyword.lower() in result.error_message.lower()
            or "select" in result.error_message.lower()
        )

    def test_rejects_multi_statement_sql_injection(self):
        """Blocks stacked multiple SQL statements to prevent injection attacks."""
        stacked_query = "SELECT * FROM customers; DROP TABLE orders;"
        result = SQLValidator.validate(stacked_query)
        assert result.is_valid is False
        assert result.error_message is not None
        error_msg = result.error_message.lower()
        assert "multi-statement" in error_msg or "forbidden" in error_msg

    def test_rejects_piggybacked_embedded_ddl(self):
        """Blocks attempts to execute administrative stored procedures or commands."""
        query = "SELECT * FROM customers; EXEC sp_configure;"
        result = SQLValidator.validate(query)
        assert result.is_valid is False
